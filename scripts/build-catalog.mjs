import fs from "node:fs";
import { createHash } from "node:crypto";
import { validatePack } from "../lib/pack-validation.mjs";
const files = ["cells-v1.json", "atoms-v1.json", "motion-v1.json"];
const packs = files.map((file) => {
  const bytes = fs.readFileSync(`public/packs/${file}`),
    p = JSON.parse(bytes);
  const errors = validatePack(p);
  if (errors.length) throw new Error(`${file}: ${errors.join("; ")}`);
  return {
    id: p.id,
    version: p.version,
    subject: p.subject,
    title: p.title,
    chapterSlug: p.chapterSlug || "cells",
    url: `/packs/${file}`,
    bytes: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
    included: p.id === "cells-starter",
    lessonIds: p.lessons.map((l) => l.id),
    questionIds: p.questions.map((q) => q.id),
    questionOptions: Object.fromEntries(
      p.questions.map((q) => [q.id, q.options.length]),
    ),
    writtenCount: p.written.length,
    verification: p.verification,
  };
});
if (
  new Set(packs.flatMap((p) => p.lessonIds)).size !==
    packs.flatMap((p) => p.lessonIds).length ||
  new Set(packs.flatMap((p) => p.questionIds)).size !==
    packs.flatMap((p) => p.questionIds).length
)
  throw new Error("Content IDs must be globally unique.");
fs.writeFileSync(
  "lib/catalog-data.mjs",
  `// Generated by scripts/build-catalog.mjs. Edit pack sources, then regenerate.\nexport default ${JSON.stringify(packs, null, 2)};\n`,
);
console.log(
  `Catalog built: ${packs.length} packs, ${packs.reduce((n, p) => n + p.lessonIds.length, 0)} lessons, ${packs.reduce((n, p) => n + p.questionIds.length, 0)} MCQs.`,
);
