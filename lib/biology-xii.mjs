export function biologyChapterTopics(bookId, number) {
  return bookId === BIOLOGY_XII ? topics[number] || [] : [];
}

export function biologyChapterCards(bookId, number, mode) {
  const rows = biologyChapterTopics(bookId, number);
  if (!rows.length) return [];
  if (mode === "long") {
    const [question, answer] = longAnswers[number];
    return [{ id: `bio-xii:${number}:long`, question, answer }];
  }
  if (mode !== "mcq" && mode !== "short") return [];
  return rows.map(
    (
      [
        sourcePage,
        topic,
        prompt,
        correctAnswer,
        distractors,
        explanation,
        recall,
      ],
      i,
    ) => {
      const correct = (number + i) % 4;
      const options = [...distractors];
      options.splice(correct, 0, correctAnswer);
      return {
        id: `bio-xii:${number}:${mode}:${i}`,
        sourcePage,
        topic,
        question: mode === "mcq" ? prompt : recall,
        answer: mode === "mcq" ? correctAnswer : explanation,
        ...(mode === "mcq" ? { options, correct, explanation } : {}),
      };
    },
  );
}
